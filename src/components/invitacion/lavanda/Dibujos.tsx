/** Una hoja con su nervadura, apoyada en (x, y) y girada. */
function hoja(x: number, y: number, grados: number, l: number, w: number) {
  const a = (grados * Math.PI) / 180, c = Math.cos(a), s = Math.sin(a);
  const q = (u: number, v: number) => `${(x + u * c - v * s).toFixed(1)} ${(y + u * s + v * c).toFixed(1)}`;
  return [
    `M${q(0, 0)}C${q(l * 0.16, -w)} ${q(l * 0.66, -w * 1.05)} ${q(l, 0)}C${q(l * 0.74, w * 0.72)} ${q(l * 0.3, w * 0.85)} ${q(0, 0)}`,
    `M${q(l * 0.06, 0)}C${q(l * 0.35, -w * 0.2)} ${q(l * 0.6, -w * 0.12)} ${q(l * 0.82, 0)}`,
  ];
}

